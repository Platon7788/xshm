/// Минимальная ёмкость кольца: одна страница.
pub const MIN_RING_CAPACITY: usize = 4 * 1024;
/// Максимальная ёмкость кольца: 1 ГиБ. Позиции кольца -- `u32` с
/// переполнением по модулю 2^32, ёмкость обязана делить 2^32 (степень двойки)
/// и быть не больше 2^31, чтобы `write - read` однозначно давало занятость.
pub const MAX_RING_CAPACITY: usize = 1024 * 1024 * 1024;

/// Минимальный размер сообщения (пустые сообщения не передаются).
pub const MIN_MESSAGE_SIZE: usize = 1;

/// Порог правила лимита `max_messages` у писателя (INTEROP §c.5, Task 18,
/// решение 28) -- часть протокола: нативный писатель обязан брать то же
/// значение.
///
/// - `max_messages <= RECOUNT_MAX`: счётчик на пределе пересчитывается по
///   кадрам окна `[read_pos, write_pos)` (не больше `2 * RECOUNT_MAX + 1`
///   заголовков: сообщения плюс не больше одного PAD между ними на обход
///   границы) -- лимит точный, отставший на 1 счётчик не вытесняет раньше;
/// - выше порога: отказ/вытеснение только при `message_count >
///   max_messages` -- законное отставание на 1 поглощается, цена -- кольцо
///   может держать `max_messages + 1` сообщение. O(1) на запись.
///
/// Значение 64: обход -- десятки наносекунд (заголовки подряд в кеше), то
/// есть порядка самой записи; при лимите больше 64 одно лишнее сообщение --
/// меньше 1,6 % лимита, а пересчёт без потолка стоил бы O(`max_messages`)
/// на запись (34 мкс при 10 000) и давал бы враждебному читателю рычаг
/// (`message_count = u32::MAX` при безлимитной конфигурации).
pub const RECOUNT_MAX: u32 = 64;

/// Размер служебного заголовка кадра: `u32 len LE` + `u32 flags`.
pub const FRAME_HEADER_SIZE: usize = 8;
/// Выравнивание кадров в кольце: позиции кадров кратны 8, поэтому заголовок
/// кадра никогда не разрывается границей кольца, а payload выровнен на 8.
pub const FRAME_ALIGN: usize = 8;
/// Бит 0 поля `flags` кадра (0.10): кадр-заполнитель (PAD). Писатель
/// вставляет его, когда кадр не помещается непрерывно до конца кольца:
/// PAD занимает остаток кольца до границы (`len` = остаток − 8, может быть
/// `0`), следующий кадр начинается с начала кольца. Читатель пропускает PAD
/// без доставки; PAD не считается сообщением (`message_count`,
/// `drop_count`, `max_messages`). Остальные биты `flags` зарезервированы и
/// обязаны быть `0` -- иначе кадр испорчен.
pub const FRAME_PAD: u32 = 1;

